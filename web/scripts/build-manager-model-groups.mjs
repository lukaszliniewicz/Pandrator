import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath, URL } from 'node:url';
import process from 'node:process';

const root = new URL('../', import.meta.url);
const output = new URL(
  '../pandrator_manager/recovery_ui/static/model-groups.js',
  root
);
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: [fileURLToPath(new URL('src/lib/local-model-groups.ts', root))],
  bundle: true,
  format: 'iife',
  globalName: 'PandratorModelGroups',
  target: 'es2022',
  write: false,
  banner: {
    js: '// Generated by web/scripts/build-manager-model-groups.mjs. Do not edit.'
  }
});
const generated = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== generated) {
    throw new Error(
      'Manager model grouping is stale. Run npm run build:manager-models in web/.'
    );
  }
} else {
  await writeFile(output, generated);
}
