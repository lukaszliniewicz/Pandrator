test('start mode flags map the explicit choice onto backend selection flags', () => {
  expect(startModeFlags('continue')).toEqual({
    missing_only: true,
    stale_only: false
  });
  expect(startModeFlags('refresh')).toEqual({
    missing_only: false,
    stale_only: true
  });
  expect(startModeFlags('all')).toEqual({
    missing_only: false,
    stale_only: false
  });
  expect(previewModeForStartMode('continue')).toBe('missing');
  expect(previewModeForStartMode('refresh')).toBe('stale');
  expect(previewModeForStartMode('all')).toBe('all');
});

