test('a slow stale preview never overrides the current choice', async ({
  page
}) => {
  const { sessionId, revisionId } = await setupSession(page);
  const canned = previewsFor(revisionId);
  const requested: string[] = [];
  await mockPreview(page, sessionId, async (body) => {
    if (body.stale_only) {
      requested.push('stale');
      await new Promise((resolve) => setTimeout(resolve, 400));
      return canned.stale;
    }
    requested.push('missing');
    return canned.missing;
  });
  await mockStart(page, sessionId, () => ({
    status: 202,
    json: startedRun(sessionId, revisionId)
  }));
  await page.goto(`/sessions/${sessionId}`);
  const dialog = await openDialog(page);
  await expect(dialog.getByTestId('generation-start-counts')).toContainText(
    '4 kept'
  );
  await dialog.getByTestId('generation-start-mode-refresh').check();
  // Mode radios stay usable during a slow refresh: switch straight back.
  await dialog.getByTestId('generation-start-mode-continue').check();
  await expect(dialog.getByTestId('generation-start-counts')).toContainText(
    '5 blocks total · 1 to generate · 4 kept'
  );
  await expect(
    dialog.getByTestId('generation-start-mode-continue')
  ).toBeChecked();
  await expect(dialog.getByTestId('generation-start-submit')).toBeEnabled();
  expect(requested).toContain('stale');
});

test('a 409 keeps its explanation and needs a new explicit click', async ({
  page
}) => {
  const { sessionId, revisionId } = await setupSession(page);
  let hash = 'hash-missing';
  await mockPreview(
    page,
    sessionId,
    () => previewsFor(revisionId, hash).missing
  );
  const started = await mockStart(page, sessionId, (_body, call) => {
    if (call === 1) {
      // The selection drifts before the next preview: no silent retry.
      hash = 'hash-missing-2';
      return {
        status: 409,
        json: {
          error: {
            code: 'generation_unavailable',
            message:
              'The selection changed while starting. Review and confirm again.'
          }
        }
      };
    }
    return { status: 202, json: startedRun(sessionId, revisionId) };
  });
  await page.goto(`/sessions/${sessionId}`);
  const dialog = await openDialog(page);
  const submit = dialog.getByTestId('generation-start-submit');
  await submit.click();
  const submitError = dialog.getByTestId('generation-start-submit-error');
  await expect(submitError).toContainText('The selection changed');
  await expect(submitError).toContainText('confirm again to start');
  expect(started).toHaveLength(1);
  // The refreshed preview requires a new explicit click with the new hash.
  await expect(submit).toBeEnabled();
  await submit.click();
  expect(started).toHaveLength(2);
  expect(started[1]).toMatchObject({
    expected_selection_hash: 'hash-missing-2'
  });
  await expect(dialog).toBeHidden();
  await page.waitForTimeout(300);
  expect(started).toHaveLength(2);
});

test('a paused run stays distinct from starting a new run', async ({
  page
}) => {
  const { sessionId, revisionId } = await setupSession(page);
  const canned = previewsFor(revisionId);
  await mockPreview(page, sessionId, () => canned.missing);
  await page.route(
    `**/api/v1/sessions/${sessionId}/generation-runs`,
    async (route) => {
      if (route.request().method() !== 'GET') return route.continue();
      await route.fulfill({
        json: {
          items: [
            {
              id: 'run-paused',
              session_id: sessionId,
              plan_revision_id: revisionId,
              sequence_number: 1,
              operation: 'generate',
              label: 'Paused run A',
              status: 'paused',
              progress: 40,
              created_at: new Date().toISOString(),
              updated_at: new Date().toISOString()
            }
          ]
        }
      });
    }
  );
  await page.goto(`/sessions/${sessionId}`);
  // Cold Windows CI loads can still be fetching route chunks after navigation.
  // Give bootstrap its own budget before asserting the paused-run controls.
  await expect(page.locator('.app-shell')).toBeVisible({ timeout: 30_000 });
  const resume = page
    .locator('.generation-drawer')
    .getByRole('button', { name: 'Resume previous run' });
  await expect(resume).toBeVisible();
  await expect(resume).toHaveAttribute(
    'title',
    'Continue the paused run with its saved voice and settings'
  );
  const dialog = await openDialog(page);
  const note = dialog.getByTestId('generation-start-resume-note');
  await expect(note).toContainText('Resume paused run is separate');
  await expect(note).toContainText('Paused run A');
  await expect(note).toContainText('saved voice and settings');
  await expect(note).toContainText('may be regenerated');
});

test('failed generation offers the safe continuation action', async ({
  page
}) => {
  const { sessionId, revisionId } = await setupSession(page);
  await mockPreview(page, sessionId, () => previewsFor(revisionId).missing);
  let startCount = 0;
  await page.route(
    `**/api/v1/sessions/${sessionId}/generation-runs`,
    async (route) => {
      if (route.request().method() === 'POST') {
        startCount += 1;
        return route.fulfill({
          status: 409,
          json: { error: { message: 'Unexpected start' } }
        });
      }
      return route.fulfill({
        json: {
          items: [
            {
              ...startedRun(sessionId, revisionId),
              id: 'failed-original-run',
              status: 'failed',
              error_message: 'A block needs correction.'
            }
          ]
        }
      });
    }
  );
  await page.goto(`/sessions/${sessionId}`);
  await page.getByRole('button', { name: 'Generation', exact: true }).click();
  const recovery = page.getByTestId('generation-recovery-continue');
  await expect(recovery).toBeVisible();
  await recovery.click();
  const dialog = page.getByTestId('generation-start-dialog');
  await expect(dialog).toBeVisible();
  await expect(
    dialog.getByTestId('generation-start-mode-continue')
  ).toBeChecked();
  await expect(dialog.getByTestId('generation-start-counts')).toContainText(
    '4 kept'
  );
  expect(startCount).toBe(0);
});

